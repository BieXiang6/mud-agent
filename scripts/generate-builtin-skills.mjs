import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const skillNames = ['customize-app-style', 'adapt-app-layout', 'write-game-script']
const target = path.join(root, 'utils', 'ai', 'builtinSkills.generated.js')

function parseSkill(name) {
  const skillDir = path.join(root, 'skills', name)
  const source = fs.readFileSync(path.join(skillDir, 'SKILL.md'), 'utf8').trim()
  const match = source.match(/^---\s*\r?\n([\s\S]*?)\r?\n---\s*(?:\r?\n|$)([\s\S]*)$/)
  if (!match) throw new Error(name + ': invalid SKILL.md frontmatter')
  const metadata = {}
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(':')
    if (separator > 0) metadata[line.slice(0, separator).trim()] = line.slice(separator + 1).trim()
  }
  if (metadata.name !== name || !metadata.description) throw new Error(name + ': missing name or description')
  const body = match[2].trim()
  const references = Array.from(body.matchAll(/\[[^\]]+\]\((references\/[A-Za-z0-9._/-]+\.md)\)/g), (entry) => entry[1])
  const bundled = Array.from(new Set(references)).map((resource) => {
    const resolved = path.resolve(skillDir, resource)
    if (!resolved.startsWith(skillDir + path.sep)) throw new Error(name + ': invalid reference path ' + resource)
    return '<reference path="' + resource + '">\n' + fs.readFileSync(resolved, 'utf8').trim() + '\n</reference>'
  })
  const content = bundled.length ? body + '\n\n## Bundled References\n\n' + bundled.join('\n\n') : body
  return { name, description: metadata.description, content, disableModelInvocation: false }
}

const generated = '// Generated by scripts/generate-builtin-skills.mjs. Do not edit directly.\n' +
  'export const BUILTIN_AI_SKILLS = Object.freeze(' + JSON.stringify(skillNames.map(parseSkill), null, 2) + ')\n'

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== generated) {
    console.error('Built-in Skill bundle is stale. Run npm run generate:skills.')
    process.exit(1)
  }
} else {
  fs.writeFileSync(target, generated, 'utf8')
  console.log('Generated ' + path.relative(root, target))
}
